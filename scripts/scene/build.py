"""Window-scene pipeline entry point: `pnpm scene:build`.

Reads only assets/window-scene/ (owner originals, never committed) and writes only public/scene/
(committed outputs) and src/content/scene-manifest.json. If any original is missing, as on
Cloudflare's build machines, it exits cleanly and leaves the committed outputs untouched.
"""
from __future__ import annotations

import hashlib
import json
import os
import sys
from collections import defaultdict

from common import CLOUDS_PIPELINE, MANIFEST, ORIGINAL_FILES, PUBLIC, ROOT, probe


def _sha256(path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def main() -> int:
    missing = [p.name for p in ORIGINAL_FILES if not p.exists()]
    if missing:
        print(f"scene:build: originals not found ({', '.join(missing)}); keeping the committed outputs in public/scene/.")
        return 0

    import clouds
    import clouds_v2
    import fly
    import grain
    import window_v2

    # The Phase 2a plate's outputs (public/scene/window/) and the other cloud pipeline's outputs are
    # left in place, unreferenced, until the owner approves v2; they are not counted in the totals.
    PUBLIC.mkdir(parents=True, exist_ok=True)
    print("scene:build: window plate v2 (frame, shade, aperture)...", flush=True)
    w = window_v2.build()
    if os.environ.get("SCENE_ONLY") == "window" and MANIFEST.exists():
        # Quick rebuild of the window layers only; the video and fly-through sections are kept as built.
        old = json.loads(MANIFEST.read_text())
        c, f, g = old["clouds"], old["fly"], old["grain"]
    else:
        print(f"scene:build: cloud loop ({CLOUDS_PIPELINE})...", flush=True)
        c = clouds_v2.build() if CLOUDS_PIPELINE == "v2" else clouds.build()
        print("scene:build: fly-through sequence...", flush=True)
        f = fly.build(tint=c.get("tint"))
        g = grain.build()

    groups: dict = defaultdict(int)
    for section, key in ((w, "window"), (c, "clouds"), (f, "fly"), (g, "grain")):
        for e in section["files"]:
            group = {"window": "plate", "clouds": "loop", "grain": "grain"}.get(key) or (
                "stills" if e["kind"] == "fly-still" else e["kind"].replace("fly-", "fly-through ")
            )
            if key == "clouds" and e["kind"] == "clouds-poster":
                group = "stills"
            if e["kind"] in ("window-shade", "window-inner"):
                group = "shade"
            groups[group] += e["bytes"]

    originals = []
    for p in ORIGINAL_FILES:
        entry = {"file": p.name, "bytes": p.stat().st_size, "sha256": _sha256(p)}
        if p.suffix == ".mp4":
            s = probe(p)["streams"][0]
            entry.update(width=s["width"], height=s["height"], fps=s["r_frame_rate"], frames=int(s["nb_frames"]))
        originals.append(entry)

    manifest = {
        "version": 2,
        "note": "Generated by scripts/scene/build.py. Do not edit by hand; see docs/WINDOW-ASSETS.md.",
        "originals": originals,
        "window": w,
        "clouds": c,
        "fly": f,
        "grain": g,
        "totals": {"bytes": sum(groups.values()), "byGroup": dict(sorted(groups.items()))},
    }
    MANIFEST.write_text(json.dumps(manifest, indent=2) + "\n")
    print(f"scene:build: done. {sum(groups.values()) / 1e6:.2f} MB in public/scene/; "
          f"manifest at {MANIFEST.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
